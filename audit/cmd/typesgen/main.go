// typesgen — génère web/frontend/src/lib/types.gen.ts à partir des structs Go
// du rapport scellé (module audit + metrics). Le miroir TS n'est plus écrit à
// la main : un champ ajouté en Go est ajouté en TS à la génération ou le
// générateur s'arrête, jamais de dérive silencieuse.
//
// La sémantique d'absence (0 = non mesuré, jamais « zéro vrai ») vit dans le
// rapport ; le générateur n'invente rien, il ne fait que refléter les tags json.
//
// Usage : go generate ./... depuis le module audit, ou :
//
//	go run ./cmd/typesgen -out ../web/frontend/src/lib/types.gen.ts
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"reflect"
	"strings"

	"github.com/Realms4239/cgo/audit"
	"github.com/Realms4239/cgo/metrics"
)

// tsName — le nom TS voulu pour un type Go ; sans entrée, le nom Go est utilisé.
// Une entrée par struct ou union mappée ; un type non mappé est une erreur,
// pas un nom Go tombant silencieusement dans le fichier.
var tsName = map[string]string{
	"Report":             "AuditReport",
	"Measured":           "AuditMeasured",
	"Phases":             "AuditPhases",
	"Unavailable":        "AuditUnavailable",
	"Provenance":         "AuditProvenance",
	"Invocation":         "AuditInvocation",
	"Remediation":        "AuditRemediation",
	"RemediationState":   "AuditRemediationState",
	"RouterOSValidation": "RouterOSValidation",
	"RouterOSCheck":      "RouterOSCheck",
	"KernelTelemetry":    "KernelTelemetry",
	"KernelFlow":         "KernelFlow",
	"Verdict":            "AuditVerdict",
	"VerdictLevel":       "AuditVerdictLevel",
	"CAPSLA":             "AuditCapsla",
	"Economics":          "AuditEconomics",
	"EconomicsScenario":  "AuditEconomicsScenario",
	"EconomicsNumbers":   "AuditEconomicsNumbers",
	"RetransRatio":       "AuditRetransRatio",
}

// unionLiterals — les unions de littéraux string : les valeurs sont celles que
// le moteur émet, jamais une liste réémise de mémoire.
var unionLiterals = map[string][]string{
	"RemediationState": {"available", "observation_only"},
	"VerdictLevel":     {"neutral", "red", "amber", "green"},
}

var roots = []reflect.Type{
	reflect.TypeOf(audit.RemediationState("")),
	reflect.TypeOf(metrics.VerdictLevel("")),
	reflect.TypeOf(audit.Report{}),
}

var unknown []string
var emitted = map[string]bool{}

func main() {
	out := flag.String("out", "", "chemin du types.gen.ts à écrire (sinon stdout)")
	flag.Parse()

	buf, err := render()
	if err != nil {
		fmt.Fprintln(os.Stderr, "typesgen:", err)
		os.Exit(2)
	}
	if *out == "" {
		os.Stdout.Write(buf)
		return
	}
	if err := os.WriteFile(*out, buf, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "typesgen:", err)
		os.Exit(1)
	}
}

// render — le fichier généré ; partagé par main() et par le test anti-dérive.
func render() ([]byte, error) {
	unknown = nil
	emitted = map[string]bool{}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by audit/cmd/typesgen. DO NOT EDIT.\n")
	buf.WriteString("// Source: les structs Go tagées json du rapport scellé (modules audit, metrics).\n")
	buf.WriteString("// La sémantique d'absence vit dans les commentaires Go (0 = non mesuré, jamais un zéro vrai)\n")
	buf.WriteString("// et dans types.ts ; ce fichier n'invente rien, il reflète les tags json.\n\n")

	for _, t := range roots {
		emit(&buf, t)
	}
	if len(unknown) > 0 {
		return nil, fmt.Errorf("types Go non mappés — ajoutez-les à tsName/unionLiterals : %s", strings.Join(unknown, ", "))
	}
	return buf.Bytes(), nil
}

func tsNameOf(goType string) string {
	if name, ok := tsName[goType]; ok {
		return name
	}
	unknown = append(unknown, goType)
	return goType // provisoire : main() échoue avant d'écrire
}

// tsType — le type TS d'une valeur Go (hors pointeurs : le champ décide).
func tsType(t reflect.Type) string {
	switch t.Kind() {
	case reflect.String:
		if _, ok := unionLiterals[t.Name()]; ok {
			return tsNameOf(t.Name())
		}
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice:
		return tsType(t.Elem()) + "[]"
	case reflect.Pointer:
		return tsType(t.Elem())
	case reflect.Struct:
		if t.Name() == "Time" {
			return "string"
		}
		return tsNameOf(t.Name())
	case reflect.Interface:
		return "unknown"
	}
	return "unknown"
}

func emit(buf *bytes.Buffer, t reflect.Type) {
	name := t.Name()
	if emitted[name] {
		return
	}
	emitted[name] = true

	// Unions de littéraux : une seule façon de dire les mots du moteur.
	if lit, ok := unionLiterals[name]; ok {
		quoted := make([]string, len(lit))
		for i, v := range lit {
			quoted[i] = fmt.Sprintf("%q", v)
		}
		fmt.Fprintf(buf, "export type %s = %s\n\n", tsNameOf(name), strings.Join(quoted, " | "))
		return
	}
	if t.Kind() != reflect.Struct {
		return
	}

	// Profondeur d'abord : les feuilles sont écrites avant leurs parents.
	for i := 0; i < t.NumField(); i++ {
		emitFieldType(buf, t.Field(i))
	}

	fmt.Fprintf(buf, "export interface %s {\n", tsNameOf(name))
	for _, f := range fields(t) {
		typ := tsType(f.typ)
		// Le verdict zéro Go émet "" : le champ est l'union quatre-mots plus la chaîne vide,
		// exactement ce que levelOf() branche en « absence ».
		if f.typ.Name() == "VerdictLevel" {
			typ = `AuditVerdictLevel | ""`
		}
		if f.ptr && !f.omit {
			fmt.Fprintf(buf, "  %s: %s | null\n", f.name, typ)
			continue
		}
		if f.omit {
			fmt.Fprintf(buf, "  %s?: %s\n", f.name, typ)
			continue
		}
		fmt.Fprintf(buf, "  %s: %s\n", f.name, typ)
	}
	buf.WriteString("}\n\n")
}

type field struct {
	name string
	typ  reflect.Type
	ptr  bool
	omit bool
}

func fields(t reflect.Type) []field {
	var out []field
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		tag := f.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name := strings.SplitN(tag, ",", 2)[0]
		if name == "" {
			name = strings.ToLower(f.Name)
		}
		omit := strings.Contains(tag, ",omitempty")
		ptr := f.Type.Kind() == reflect.Pointer
		out = append(out, field{name: name, typ: f.Type, ptr: ptr, omit: omit})
	}
	return out
}

func emitFieldType(buf *bytes.Buffer, f reflect.StructField) {
	t := f.Type
	for {
		switch t.Kind() {
		case reflect.Pointer, reflect.Slice:
			t = t.Elem()
			continue
		}
		break
	}
	if t.Kind() == reflect.Struct && t.Name() != "Time" {
		emit(buf, t)
	}
}
